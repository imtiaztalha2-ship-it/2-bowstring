# Stage 3: pick best string per note & layer, pack into one Ogg Vorbis stream + SampleMap.h
from common import *
import pickle, json, subprocess, soundfile as sf, os
from collections import defaultdict
SR = 44100
R = pickle.load(open('processed.pkl','rb'))
for r in R:
    if r['art']=='pizz':   # level-match pizz by its pluck peak (crest factor varies a lot)
        r['gain'] = 0.6/max(np.percentile(np.abs(r['audio'][:int(0.2*SR)]), 99.9), 1e-6)
lim = lambda r: 300 if r['art']=='arco' else 40
bad = [r for r in R if r['gain'] > lim(r)]
print('rejected (too quiet / noise only):', len(bad))
R = [r for r in R if r['gain'] <= lim(r)]
LAY = {'pp':0,'mf':1,'ff':2}
chosen = []
for art in ('arco','pizz'):
    by = defaultdict(list)
    for r in R:
        if r['art']==art: by[r['midi']].append(r)
    for m in sorted(by):
        cs = by[m]
        # string choice: the string that gives the best combined result over pp/mf/ff
        strings = set(r['string'] for r in cs)
        def string_score(st):
            tot = 0
            for L in LAY:
                sc = [r['score'] for r in cs if r['string']==st and r['dyn']==L]
                tot += max(sc) if sc else -3.0
            return tot
        st = max(strings, key=string_score)
        for L in LAY:
            pool = [r for r in cs if r['dyn']==L and r['string']==st] or [r for r in cs if r['dyn']==L]
            if not pool: continue
            best = max(pool, key=lambda r: r['score'])
            chosen.append(best)
print(len(chosen), 'samples chosen')
summary = defaultdict(dict)
for c in chosen: summary[(c['art'],c['midi'])][c['dyn']] = f"{c['string']}{'*' if c['src']=='2012' else ''}"
for k in sorted(summary): print(k[0], midi2name(k[1]), summary[k])

# pack
pad = 256
chunks=[]; entries=[]; off=0
for c in sorted(chosen, key=lambda c:(c['art'], LAY[c['dyn']], c['midi'])):
    y = (c['audio']*c['gain']).astype(np.float32)
    entries.append(dict(artic=0 if c['art']=='arco' else 1, layer=LAY[c['dyn']], midi=c['midi'], rootHz=c['f0'],
                        offset=off, length=len(y), loopStart=c['loopStart'], loopEnd=c['loopEnd'],
                        legatoStart=c['legatoStart'], gain=1.0, string=c['string'], src=c['src'], file=c['file'],
                        quality=c['quality']))
    chunks.append(y); chunks.append(np.zeros(pad, np.float32)); off += len(y)+pad
pack = np.concatenate(chunks)
peak = np.abs(pack).max(); print('peak', peak, 'seconds', len(pack)/SR)
if peak > 0.98:
    pack *= 0.98/peak
    for e in entries: e['gain'] = float(peak/0.98)   # restored at load time
sf.write('pack.wav', pack, SR, subtype='PCM_16')
subprocess.run(['oggenc','-Q','-q','5','-o','violin_pack.ogg','pack.wav'], check=True)
subprocess.run(['flac','-s','-f','-8','-o','pack.flac','pack.wav'], check=True)
print('ogg', os.path.getsize('violin_pack.ogg')//1024, 'KB  flac', os.path.getsize('pack.flac')//1024, 'KB')
json.dump(dict(total=len(pack), entries=entries), open('pack.json','w'), indent=1)

hdr = ['#pragma once',
'// Generated by tools/sample_pipeline/build_samples.sh from the University of Iowa Musical Instrument Samples (violin).',
'// Do not edit by hand.',
'#include "BinaryData.h"','',
'namespace samplemap','{',
'struct Entry { int artic, layer, midi; float rootHz; int offset, length, loopStart, loopEnd, legatoStart; float gain; };','',
f'inline constexpr int sampleRate   = {SR};',
f'inline constexpr int totalSamples = {len(pack)};',
f'inline constexpr int numSamples   = {len(entries)};','',
'// artic 0 = arco, 1 = pizz; layer 0 = pp, 1 = mf, 2 = ff; offsets/lengths in samples at sampleRate',
'inline constexpr Entry entries[] = {']
for e in entries:
    hdr.append(f"    {{ {e['artic']}, {e['layer']}, {e['midi']:3d}, {e['rootHz']:9.3f}f, {e['offset']:8d}, {e['length']:6d}, {e['loopStart']:6d}, {e['loopEnd']:6d}, {e['legatoStart']:6d}, {e['gain']:.5f}f }}, // {midi2name(e['midi'])} sul{e['string']} {e['src']}")
hdr += ['};','',
'inline const char* const packData = BinaryData::violin_pack_ogg;',
'inline const int packSize = BinaryData::violin_pack_oggSize;',
'} // namespace samplemap','']
open('SampleMap.h','w').write('\n'.join(hdr))
